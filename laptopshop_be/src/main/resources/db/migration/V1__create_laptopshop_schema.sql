-- LaptopShopDB: SQL Server schema converted to PostgreSQL for Flyway.
-- Initial migration for a new, empty Supabase PostgreSQL database.
-- Do not run the original SQL Server script against PostgreSQL.

CREATE TABLE brands (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL,
                        description VARCHAR(500),
                        status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                        created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP(6),
                        CONSTRAINT uq_brands_name UNIQUE (name),
                        CONSTRAINT ck_brands_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL,
                            description VARCHAR(500),
                            status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                            created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at TIMESTAMP(6),
                            CONSTRAINT uq_categories_name UNIQUE (name),
                            CONSTRAINT ck_categories_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       full_name VARCHAR(150) NOT NULL,
                       email VARCHAR(150) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       phone VARCHAR(20) NOT NULL,
                       address VARCHAR(500),
                       role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER',
                       status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                       created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMP(6),
                       CONSTRAINT uq_users_email UNIQUE (email),
                       CONSTRAINT ck_users_email_not_blank CHECK (BTRIM(email) <> '' AND email LIKE '%_@__%.__%'),
                       CONSTRAINT ck_users_password_hash_bcrypt CHECK (
                           password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'
),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'CUSTOMER')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE laptops (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         sku VARCHAR(50) NOT NULL,
                         name VARCHAR(255) NOT NULL,
                         brand_id BIGINT NOT NULL,
                         category_id BIGINT NOT NULL,
                         specs VARCHAR(500) NOT NULL,
                         description TEXT,
                         image VARCHAR(500),
                         price NUMERIC(18,2) NOT NULL,
                         old_price NUMERIC(18,2),
                         stock_quantity INTEGER NOT NULL DEFAULT 0,
                         status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
                         created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         updated_at TIMESTAMP(6),
                         CONSTRAINT uq_laptops_sku UNIQUE (sku),
                         CONSTRAINT fk_laptops_brands FOREIGN KEY (brand_id) REFERENCES brands(id),
                         CONSTRAINT fk_laptops_categories FOREIGN KEY (category_id) REFERENCES categories(id),
                         CONSTRAINT ck_laptops_old_price CHECK (old_price IS NULL OR old_price > 0),
                         CONSTRAINT ck_laptops_price CHECK (price > 0),
                         CONSTRAINT ck_laptops_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
                         CONSTRAINT ck_laptops_stock_quantity CHECK (stock_quantity >= 0)
);

CREATE TABLE cart_items (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            user_id BIGINT NOT NULL,
                            laptop_id BIGINT NOT NULL,
                            quantity INTEGER NOT NULL,
                            created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at TIMESTAMP(6),
                            CONSTRAINT uq_cart_items_user_laptop UNIQUE (user_id, laptop_id),
                            CONSTRAINT fk_cart_items_users FOREIGN KEY (user_id) REFERENCES users(id),
                            CONSTRAINT fk_cart_items_laptops FOREIGN KEY (laptop_id) REFERENCES laptops(id),
                            CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);

CREATE TABLE wishlist_items (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                user_id BIGINT NOT NULL,
                                laptop_id BIGINT NOT NULL,
                                created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                CONSTRAINT uq_wishlist_items_user_laptop UNIQUE (user_id, laptop_id),
                                CONSTRAINT fk_wishlist_items_users FOREIGN KEY (user_id) REFERENCES users(id),
                                CONSTRAINT fk_wishlist_items_laptops FOREIGN KEY (laptop_id) REFERENCES laptops(id)
);

CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001 INCREMENT BY 1) PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        order_date TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        receiver_name VARCHAR(150) NOT NULL,
                        phone VARCHAR(20) NOT NULL,
                        address VARCHAR(500) NOT NULL,
                        payment_method VARCHAR(30) NOT NULL DEFAULT 'COD',
                        total_amount NUMERIC(18,2) NOT NULL,
                        status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                        created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP(6),
                        CONSTRAINT fk_orders_users FOREIGN KEY (user_id) REFERENCES users(id),
                        CONSTRAINT ck_orders_payment_method CHECK (payment_method = 'COD'),
                        CONSTRAINT ck_orders_status CHECK (
                            status IN ('PENDING', 'CONFIRMED', 'PACKING', 'SHIPPING', 'COMPLETED', 'CANCELLED')
                            ),
                        CONSTRAINT ck_orders_total_amount CHECK (total_amount >= 0)
);

CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL,
                             laptop_id BIGINT NOT NULL,
                             product_name VARCHAR(255) NOT NULL,
                             unit_price NUMERIC(18,2) NOT NULL,
                             quantity INTEGER NOT NULL,
                             CONSTRAINT fk_order_items_orders FOREIGN KEY (order_id) REFERENCES orders(id),
                             CONSTRAINT fk_order_items_laptops FOREIGN KEY (laptop_id) REFERENCES laptops(id),
                             CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
                             CONSTRAINT ck_order_items_unit_price CHECK (unit_price > 0)
);

CREATE TABLE refresh_tokens (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                token_hash VARCHAR(64) NOT NULL,
                                user_id BIGINT NOT NULL,
                                created_at TIMESTAMPTZ(6) NOT NULL,
                                expires_at TIMESTAMPTZ(6) NOT NULL,
                                revoked_at TIMESTAMPTZ(6),
                                CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
                                CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX ix_laptops_brand_category_status ON laptops(status, brand_id, category_id);
CREATE INDEX ix_orders_user_status_date ON orders(user_id, status, order_date DESC);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens(user_id);
